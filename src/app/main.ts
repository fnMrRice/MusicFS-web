import { createLayout } from '../ui/layout';
import { Application } from './bootstrap';
import { LibraryApi } from '../api/library';
import { LibraryController } from '../library/controller';
import { FileListView } from '../ui/file-list';
import { PlaybackApi } from '../api/playback';
import { PlayerController } from '../player/controller';
import { PlayerView } from '../ui/player-view';
import { audioFactory } from '../player/audio-adapter';
import { capabilities } from '../player/capabilities';
import '../ui/styles.css';

const app = document.querySelector<HTMLElement>('#app');
if (!app) throw new Error('Missing application root');
const layout = createLayout(app);
const application = new Application(layout);
const library = new LibraryController(new LibraryApi(application.client), new FileListView(layout.library));
application.onLogin = () => library.open();
const playerView = new PlayerView(layout.player);
const player = new PlayerController(new PlaybackApi(application.client), audioFactory(playerView.audioRoot), capabilities(document.createElement('audio')));
player.onChange = () => playerView.render(player.state);
playerView.stop.onclick = () => player.stop();
playerView.jump.onclick = () => player.seek(Number(playerView.position.value) * 1000);
library.view.onPlay = (track) => { void player.select(track); };
application.onLogout = () => { player.stop(); library.clear(); };
playerView.render(player.state);
window.addEventListener('pagehide', () => player.stop());
void application.connect();
